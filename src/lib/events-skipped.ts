/**
 * 「有记录读不出来」提示文案（R14 B2-3 / Q9-08）——前后端共用的纯函数模块（无 server-only 依赖）。
 *
 * 服务端读 events.jsonl 时遇到「非空但解析不了」的行（崩溃半行 / 断电后的全 0 填充 / 磁盘问题）：
 * 以前悄悄跳过，用户只看到对话少了一截、不知道为什么；现在 `Task.eventsSkipped` 带上条数，界面画一条灰色提示
 * （`EventsSkippedNotice`）。
 *
 * 口径要写进文案，别让人误会成「整份历史里一共坏了 N 条」：
 * - 条数只覆盖**已加载的这一段**（长任务只读尾部切片，更早的历史没去数）→ 写「至少 N 处」、不写「共 N 条」；
 * - 一大段连续的坏数据（如断电后的全 0 填充）只算 1 处，所以单位是「处」不是「条」。
 * 文案不出现文件路径 / 字节偏移 / 行内容——那些只进服务端日志。
 */

export interface EventsSkippedCopy {
  /** 一句话标题 */
  title: string;
  /** 补充说明：多半是什么原因、对其余内容有没有影响、统计口径 */
  detail: string;
}

export const describeEventsSkipped = (count: number): EventsSkippedCopy => ({
  title: `至少有 ${count} 处记录读不出来，已跳过`,
  detail:
    "多半是电脑崩溃、断电或磁盘问题留下的残缺数据。其余内容不受影响，那几处还留在原文件里。" +
    "这里只数了已加载的部分（长对话只读最近一段），更早的历史没有统计。",
});
